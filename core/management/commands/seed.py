class Command(BaseCommand):
    help = "Наполняет сайт стартовым контентом (правила, термины, наказания, примеры)."

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true", help="пересоздать всё заново")

    @transaction.atomic
    def handle(self, *args, **opts):
        if Channel.objects.exists():
            if not opts["reset"]:
                self.stdout.write("База уже наполнена. Для пересоздания: python3 manage.py seed --reset")
                return
            Achievement.objects.all().delete()
            Sentence.objects.all().delete()
            FridaySession.objects.all().delete()
            Punishment.objects.all().delete()
            Podsos.objects.all().delete()
            Term.objects.all().delete()
            Post.objects.all().delete()
            Channel.objects.all().delete()
            Member.objects.all().delete()

        # ---- участники
        me = Member.objects.create(name="хозяин пространства", slug="me", emoji="🙂", color="#5865f2", status="правит правила", order=0)
        friend = Member.objects.create(name="друг", slug="friend", emoji="😎", color="#23a55a", status="ждёт пятницу", order=1)

        # ---- каналы
        def ch(name, slug, kind, icon, category, desc, order):
            return Channel.objects.create(name=name, slug=slug, kind=kind, icon=icon, category=category, description=desc, order=order)

        rules = ch("правила-мазохизма", "rules", Channel.KIND_RULES, "#", "ПРАВИЛА", "Политика любительского мазохизма", 0)
        oon = ch("оон", "oon", Channel.KIND_RULES, "📕", "ПРАВИЛА", "Общее определение наказания", 1)
        defs = ch("определения", "definitions", Channel.KIND_GLOSSARY, "📖", "ПРАВИЛА", "Список определений и терминов", 2)
        puns = ch("список-наказаний", "punishments", Channel.KIND_PUNISHMENTS, "💀", "НАКАЗАНИЯ", "Что может выпасть в кол", 3)
        wheel = ch("колесо", "wheel", Channel.KIND_WHEEL, "🌀", "НАКАЗАНИЯ", "Крутим столько раз, сколько оп", 4)
        prog = ch("прогресс", "progress", Channel.KIND_PROGRESS, "📊", "НАКАЗАНИЯ", "Мероприятия, оп, отработки", 5)
        ach = ch("достижения", "achievements", Channel.KIND_ACHIEVEMENTS, "🏆", "НАКАЗАНИЯ", "За каждое достигнутое наказание", 6)
        pod = ch("подсос", "podsos", Channel.KIND_SUBSOS, "🎲", "ПРОЧЕЕ", "Подсостояния ДОПОЛНИТЕЛЬНОГО сос", 7)
        gen = ch("общий", "general", Channel.KIND_CHAT, "💬", "ПРОЧЕЕ", "Всё остальное", 8)

        # ---- термины
        for i, (short, title, definition) in enumerate(TERMS):
            Term.objects.create(short=short, title=title, definition=definition, order=i)

        # ---- правила и оон
        for chn, author, items in [
            (rules, me, [(RULES_1, True), (RULES_2, False), (RULES_3, False)]),
            (oon, me, [(OON_1, False), (OON_2, True)]),
            (gen, friend, [(GENERAL_1, False)]),
        ]:
            for content, pinned in items:
                Post.objects.create(channel=chn, author=author, content=content, pinned=pinned)

        # ---- подсосы
        podsos = [
            Podsos.objects.create(title=t, description=d, order=i) for i, (t, d) in enumerate(PODSOS)
        ]

        # ---- наказания
        pun_objs = []
        for i, (title, kind, val, seasons, link, status, weight, desc) in enumerate(PUNS):
            p = Punishment(
                title=title,
                kind=kind,
                description=desc,
                link=link,
                seasons_note=seasons,
                status=status,
                weight=weight,
                order=i,
            )
            if kind == Punishment.KIND_SERIES:
                p.episode_minutes = val
            elif kind == Punishment.KIND_MOVIE:
                p.duration_minutes = val
            p.save()
            pun_objs.append(p)

        # ---- примеры мероприятий
        f1, f2 = last_friday(), last_friday(last_friday() - timedelta(days=1))
        s1 = FridaySession.objects.create(
            date=f2, tiktoks=150, laughs=6, extra_podsos=podsos[0],
            notes="Тиктоков маловато — включилось ДОПОЛНИТЕЛЬНОЕ сос, выбран один подсос.",
        )
        s2 = FridaySession.objects.create(
            date=f1, tiktoks=240, laughs=9,
            notes="Обычная пятница. Ос хватило на четыре кола.",
        )

        # ---- отработки и достижения
        x1 = Sentence.objects.create(session=s1, punishment=pun_objs[4], spins=1)
        x1.status = Sentence.STATUS_DONE
        x1.watched_units = x1.planned_units
        from django.utils import timezone

        x1.completed_at = timezone.now()
        x1.save()
        logic.award_for_sentence(x1)

        Sentence.objects.create(session=s2, punishment=pun_objs[0], spins=2, watched_units=2,
                                status=Sentence.STATUS_IN_PROGRESS, note="Смотрим по паре серий в неделю.")
        Sentence.objects.create(session=s2, punishment=pun_objs[3], spins=1, watched_units=40,
                                status=Sentence.STATUS_IN_PROGRESS)

        self.stdout.write(self.style.SUCCESS("Готово: правила, термины, наказания и примеры на месте."))
        self.stdout.write("Ключ правки по умолчанию: friday (поменять: FDZHTT_EDIT_CODE).")
